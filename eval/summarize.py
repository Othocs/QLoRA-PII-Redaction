"""Build results/SUMMARY.md and the README results table from results/*.json.

python -m eval.summarize
"""

from __future__ import annotations

import json
import re
from pathlib import Path

SYSTEM_NAMES = {
    "presidio": "Presidio",
    "gliner_knowledgator": "GLiNER-PII (Knowledgator)",
    "gliner_nvidia": "GLiNER-PII (NVIDIA)",
    "openmed": "OpenMed privacy filter v2",
    "base_llm": "Base LLM, zero-shot",
    "lora": "Your LoRA model",
    "lora_validators": "Your LoRA model + validators",
    "lora_r16_10k_1.7b": "LoRA r16, 10k (Qwen3-1.7B)",
    "m0_openpii10k": "M0 OpenPII 10k",
    "m1_clean10k": "M1 cleaned OpenPII 10k",
    "m2_mix10k": "M2 cleaned OpenPII 5k + Nemotron 5k",
    "m3_mix20k": "M3 cleaned OpenPII 10k + Nemotron 10k",
}
# The adapter shown as "Your LoRA model" in the README table (results are tagged per run).
README_LORA_TAG = "lora_r16_10k_1.7b"
OOD_SETS = [
    ("test_holdout_regions", "OpenPII, region IN"),
    ("nemotron", "Nemotron-PII"),
    ("tab", "TAB (real ECHR)"),
    ("gretel_en", "Gretel EN"),
    ("gretel_xx", "Gretel non-EN"),
    ("openpii_xx", "OpenPII non-EN"),
]
README_BEGIN, README_END = "<!-- RESULTS_TABLE:BEGIN -->", "<!-- RESULTS_TABLE:END -->"


def _pct(x: float | None) -> str:
    return "" if x is None else f"{100 * x:.1f}"


def _f(x: float | None, nd: int = 3) -> str:
    return "" if x is None else f"{x:.{nd}f}"


def load(results_dir: Path) -> dict[tuple[str, str], dict]:
    out = {}
    for p in sorted(results_dir.glob("*__*.json")):
        r = json.loads(p.read_text())
        out[(r["system"], r["testset"])] = r
    return out


def summary_md(res: dict[tuple[str, str], dict]) -> str:
    lines = [
        "# Results summary",
        "",
        "Generated by `python -m eval.summarize`; do not edit by hand. Leakage = share of gold",
        "PII characters left unmasked (lower is better). Latency is per 1,000 characters.",
        "",
        "| System | Test set | N | Leakage chars % | Docs leaking % | Over-redaction % |"
        " Strict F1 | Partial F1 | p50 ms | p95 ms | Platform |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for (system, ts), r in sorted(res.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        m, lat = r["metrics"], r["latency"]
        lines.append(
            f"| {SYSTEM_NAMES.get(system, system)} | {ts} | {r['n_examples']} | "
            f"{_pct(m['leakage_chars'])} | {_pct(m['leakage_docs'])} | "
            f"{_pct(m['over_redaction'])} | "
            f"{_f(m['strict']['f1'])} | {_f(m['partial']['f1'])} | "
            f"{_f(lat['p50_ms_per_1k_chars'], 0)} | {_f(lat['p95_ms_per_1k_chars'], 0)} | "
            f"{r['env']['platform']} |"
        )
    lines += ood_tables(res)
    lines += ablation_table(res)
    return "\n".join(lines) + "\n"


def ood_tables(res: dict[tuple[str, str], dict]) -> list[str]:
    """Leakage pivot over the out-of-distribution sets, then per-language leakage."""
    systems = sorted({s for s, ts in res if ts in dict(OOD_SETS)})
    if not systems:
        return []
    out = [
        "",
        "## Out-of-distribution leakage (%)",
        "",
        "Each cell is leakage / partial F1; n/a means not run (Presidio is English-only here).",
        "",
        "| System | " + " | ".join(label for _, label in OOD_SETS) + " |",
        "| --- |" + " ---: |" * len(OOD_SETS),
    ]
    for system in systems:
        cells = []
        for ts, _ in OOD_SETS:
            r = res.get((system, ts))
            m = r["metrics"] if r else None
            cells.append(
                f"{_pct(m['leakage_chars'])} / {_f(m['partial']['f1'], 2)}" if m else "n/a"
            )
        out.append(f"| {SYSTEM_NAMES.get(system, system)} | " + " | ".join(cells) + " |")
    for ts in ("gretel_xx", "openpii_xx"):
        langs = sorted(
            {
                lang
                for (s, t), r in res.items()
                if t == ts
                for lang in r["metrics"].get("per_language", {})
            }
        )
        if not langs:
            continue
        out += ["", f"### {dict(OOD_SETS)[ts]}: leakage (%) by language", ""]
        out.append("| System | " + " | ".join(langs) + " |")
        out.append("| --- |" + " ---: |" * len(langs))
        for system in systems:
            r = res.get((system, ts))
            if not r:
                continue
            per = r["metrics"].get("per_language", {})
            cells = [_pct(per[lang]["leakage_chars"]) if lang in per else "" for lang in langs]
            out.append(f"| {SYSTEM_NAMES.get(system, system)} | " + " | ".join(cells) + " |")
    return out


ABLATION = ["m0_openpii10k", "m1_clean10k", "m2_mix10k", "m3_mix20k"]
ABLATION_SETS = [
    ("dev", "OpenPII dev"),
    ("gretel_dev", "Gretel dev (selection)"),
    ("test_holdout_regions", "OpenPII IN"),
    ("openpii_xx", "OpenPII non-EN"),
    ("nemotron", "Nemotron ¹"),
    ("tab", "TAB"),
    ("gretel_en", "Gretel EN"),
    ("gretel_xx", "Gretel non-EN"),
]


def ablation_table(res: dict[tuple[str, str], dict]) -> list[str]:
    """Week 3 part B: same model and recipe, different training data."""
    rows = [m for m in ABLATION if any((m, ts) in res for ts, _ in ABLATION_SETS)]
    if not rows:
        return []
    out = [
        "",
        "## Training-data ablation (leakage % / over-redaction %)",
        "",
        "Qwen3-1.7B, QLoRA r=16, 1 epoch; only the training data differs. ¹ Nemotron train is "
        "in M2/M3's training data, so Nemotron test is in-distribution for them.",
        "",
        "| Model | " + " | ".join(label for _, label in ABLATION_SETS) + " |",
        "| --- |" + " ---: |" * len(ABLATION_SETS),
    ]
    for m in rows:
        cells = []
        for ts, _ in ABLATION_SETS:
            r = res.get((m, ts))
            mm = r["metrics"] if r else None
            cells.append(
                f"{_pct(mm['leakage_chars'])} / {_pct(mm['over_redaction'])}" if mm else ""
            )
        out.append(f"| {SYSTEM_NAMES.get(m, m)} | " + " | ".join(cells) + " |")
    return out


def readme_table(res: dict[tuple[str, str], dict]) -> str:
    def leak(system: str, ts: str) -> str:
        r = res.get((system, ts))
        return _pct(r["metrics"]["leakage_chars"]) if r else ""

    def sd_f1(system: str) -> str:
        r = res.get((system, "support_desk"))
        return _f(r["metrics"]["strict"]["f1"]) if r else ""

    def p95(system: str) -> str:
        # Prefer the in-distribution test set; CPU numbers only (GPU runs go in their own table).
        for ts in ("test_id", "dev"):
            r = res.get((system, ts))
            gpu_only = r and r.get("detector") in ("base_llm", "lora")  # vLLM runs are GPU
            if r and not gpu_only and r["env"]["device"] in ("cpu", "default"):
                return _f(r["latency"]["p95_ms_per_1k_chars"], 0)
        return ""

    lines = [
        "| System | Leakage, OpenPII (%) | Leakage, held-out region IN (%) |"
        " Leakage, Nemotron-PII (%) | Leakage, support desk (%) | Strict F1, support desk |"
        " p95 latency CPU (ms / 1k chars) | Cost ($ / 1M chars) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for key, label in SYSTEM_NAMES.items():
        if key == "lora":
            key = README_LORA_TAG
        lines.append(
            f"| {label} | {leak(key, 'test_id')} | {leak(key, 'test_holdout_regions')} | "
            f"{leak(key, 'nemotron')} | {leak(key, 'support_desk')} | {sd_f1(key)} | "
            f"{p95(key)} |  |"
        )
    return "\n".join(lines)


def summarize(results_dir: Path = Path("results"), readme: Path | None = None) -> None:
    """Write SUMMARY.md; also refresh the README table when `readme` is given."""
    res = load(results_dir)
    (results_dir / "SUMMARY.md").write_text(summary_md(res))
    if readme is not None and readme.exists():
        doc = readme.read_text()
        if README_BEGIN in doc:
            doc = re.sub(
                re.escape(README_BEGIN) + r".*?" + re.escape(README_END),
                f"{README_BEGIN}\n{readme_table(res)}\n{README_END}",
                doc,
                flags=re.S,
            )
            readme.write_text(doc)


if __name__ == "__main__":
    summarize(Path("results"), Path("README.md"))
